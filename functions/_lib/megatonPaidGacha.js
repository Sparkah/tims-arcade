export function paidGachaSpec(productId) {
  return PAID_PRODUCT_SPECS[String(productId || '')] || null;
}

export function secureRandomBelow(maxExclusive, cryptoApi = globalThis.crypto) {
  const max = Number(maxExclusive);
  if (!Number.isSafeInteger(max) || max <= 0 || max > 0x100000000) {
    throw new RangeError('invalid_secure_random_bound');
  }
  if (!cryptoApi || typeof cryptoApi.getRandomValues !== 'function') {
    throw new Error('secure_random_unavailable');
  }

  const range = 0x100000000;
  const limit = range - (range % max);
  const words = new Uint32Array(1);
  do {
    cryptoApi.getRandomValues(words);
  } while (words[0] >= limit);
  return words[0] % max;
}

function pickRarity(tableName, randomBelow) {
  const table = DROP_TABLES[tableName];
  if (!table) throw new Error('unknown_megaton_drop_table');
  let ticket = randomBelow(1000000);
  for (const [rarity, weight] of table) {
    if (ticket < weight) return rarity;
    ticket -= weight;
  }
  return table[table.length - 1][0];
}

export function rollMegatonPaidProduct(productId, randomBelow = secureRandomBelow) {
  const spec = paidGachaSpec(productId);
  if (!spec) return null;
  const rolls = [];
  for (let index = 0; index < spec.rolls; index += 1) {
    const rarity = pickRarity(spec.table, randomBelow);
    const pool = CATALOG_BY_RARITY[rarity];
    const item = pool[randomBelow(pool.length)];
    rolls.push({
      index,
      itemId: item.id,
      name: item.name,
      rarity: item.rarity,
      boost: { ...item.boost },
    });
  }
  return rolls;
}

export function paidPurchaseAmountMatches(purchase, product) {
  if (!purchase || !product || purchase.status !== 'paid') return false;
  const currency = String(purchase.currency || '').toUpperCase();
  if (currency === 'XTR') {
    return Number.isSafeInteger(Number(product.amount))
      && Number(purchase.total_amount) === Number(product.amount);
  }
  if (currency === 'TON' || currency === 'TON_CREDIT') {
    try {
      return BigInt(String(purchase.total_amount || '0')) === BigInt(String(product.nanotons || '0'));
    } catch {
      return false;
    }
  }
  return false;
}

export async function listPaidMegatonGachaPurchases(
  env,
  telegramUserId,
  cutoverAt,
  limit = MEGATON_PAID_RECONCILE_LIMIT,
) {
  const boundedLimit = Math.max(1, Math.min(
    MEGATON_PAID_RECONCILE_LIMIT,
    Math.floor(Number(limit) || MEGATON_PAID_RECONCILE_LIMIT),
  ));
  const rows = await supabaseRequest(env, 'rpc/list_unredeemed_megaton_paid_gacha', {
    method: 'POST',
    headers: { prefer: 'return=representation' },
    body: JSON.stringify({
      p_telegram_user_id: String(telegramUserId),
      p_cutover_at: String(cutoverAt),
      p_limit: boundedLimit,
    }),
  });
  return Array.isArray(rows) ? rows : [];
}

export async function redeemMegatonPaidGacha(env, purchase, proposedRolls, cutoverAt) {
  const rows = await supabaseRequest(env, 'rpc/redeem_megaton_paid_gacha', {
    method: 'POST',
    headers: { prefer: 'return=representation' },
    body: JSON.stringify({
      p_purchase_payload: purchase.payload,
      p_telegram_user_id: purchase.telegram_user_id,
      p_product_id: purchase.product_id,
      p_catalog_version: MEGATON_PAID_GACHA_CATALOG_VERSION,
      p_cutover_at: String(cutoverAt || ''),
      p_rolls: proposedRolls,
    }),
  });
  return Array.isArray(rows) && rows.length ? rows[0] : null;
}

function safeInventoryCounter(value, field) {
  let counter = null;
  if (typeof value === 'number' && Number.isSafeInteger(value) && value >= 0) {
    counter = value;
  } else if (typeof value === 'string' && /^(0|[1-9]\d*)$/.test(value)) {
    const parsed = BigInt(value);
    if (parsed <= BigInt(Number.MAX_SAFE_INTEGER)) counter = Number(parsed);
  }
  if (counter === null) {
    const error = new Error(`Invalid Megaton paid inventory ${field}`);
    error.code = 'invalid_paid_inventory_snapshot';
    throw error;
  }
  return counter;
}

function publicPaidInventoryRows(rows) {
  if (!Array.isArray(rows) || rows.length > MEGATON_PAID_INVENTORY_MAX_ITEMS) {
    const error = new Error('Invalid Megaton paid inventory row count');
    error.code = 'invalid_paid_inventory_snapshot';
    throw error;
  }

  const seen = new Set();
  return rows.map((row) => {
    const itemId = String(row && row.item_id || '');
    const rarity = String(row && row.rarity || '');
    const catalogItem = CATALOG_BY_ID[itemId];
    const paidCopies = safeInventoryCounter(row && row.paid_copies, 'paid_copies');
    if (!catalogItem || catalogItem.rarity !== rarity || paidCopies < 1 || seen.has(itemId)) {
      const error = new Error('Invalid Megaton paid inventory row');
      error.code = 'invalid_paid_inventory_snapshot';
      throw error;
    }
    seen.add(itemId);
    return { itemId, rarity, paidCopies };
  });
}

function publicPaidInventoryStats(rows, inventory) {
  if (!Array.isArray(rows) || rows.length > 1) {
    const error = new Error('Invalid Megaton paid inventory stats row count');
    error.code = 'invalid_paid_inventory_snapshot';
    throw error;
  }
  if (!rows.length) {
    if (inventory.length) {
      const error = new Error('Missing Megaton paid inventory stats');
      error.code = 'invalid_paid_inventory_snapshot';
      throw error;
    }
    return { totalPaidRolls: 0, uniquePaidItems: 0, duplicatePaidRolls: 0 };
  }

  const row = rows[0];
  const stats = {
    totalPaidRolls: safeInventoryCounter(row.total_paid_rolls, 'total_paid_rolls'),
    uniquePaidItems: safeInventoryCounter(row.unique_paid_items, 'unique_paid_items'),
    duplicatePaidRolls: safeInventoryCounter(row.duplicate_paid_rolls, 'duplicate_paid_rolls'),
  };
  let paidCopyTotal = 0;
  for (const item of inventory) {
    paidCopyTotal += item.paidCopies;
    if (!Number.isSafeInteger(paidCopyTotal)) {
      const error = new Error('Megaton paid inventory total exceeds safe integer range');
      error.code = 'invalid_paid_inventory_snapshot';
      throw error;
    }
  }
  if (
    stats.uniquePaidItems !== inventory.length
    || stats.totalPaidRolls !== paidCopyTotal
    || stats.uniquePaidItems + stats.duplicatePaidRolls !== stats.totalPaidRolls
  ) {
    const error = new Error('Inconsistent Megaton paid inventory stats');
    error.code = 'invalid_paid_inventory_snapshot';
    throw error;
  }
  return stats;
}

export async function getPaidMegatonInventorySnapshot(env, telegramUserId) {
  const inventoryParams = new URLSearchParams({
    select: 'item_id,rarity,paid_copies',
    telegram_user_id: `eq.${String(telegramUserId)}`,
    order: 'item_id.asc',
    limit: String(MEGATON_PAID_INVENTORY_MAX_ITEMS + 1),
  });
  const inventoryRows = await supabaseRequest(
    env,
    `telegram_megaton_paid_inventory?${inventoryParams.toString()}`,
    { method: 'GET' },
  );
  const inventory = publicPaidInventoryRows(inventoryRows);

  const statsParams = new URLSearchParams({
    select: 'total_paid_rolls,unique_paid_items,duplicate_paid_rolls',
    telegram_user_id: `eq.${String(telegramUserId)}`,
    limit: '1',
  });
  const statsRows = await supabaseRequest(
    env,
    `telegram_megaton_paid_inventory_stats?${statsParams.toString()}`,
    { method: 'GET' },
  );

  return {
    catalogVersion: MEGATON_PAID_GACHA_CATALOG_VERSION,
    items: inventory,
    stats: publicPaidInventoryStats(statsRows, inventory),
  };
}

export function publicPaidGachaReceipt(row) {
  if (!row) return null;
  return {
    receiptId: row.receipt_id,
    productId: row.product_id,
    catalogVersion: row.catalog_version,
    rolls: Array.isArray(row.rolls) ? row.rolls : [],
    rollCount: Number(row.roll_count || 0),
    createdAt: row.created_at,
    idempotent: Boolean(row.idempotent),
    payment: {
      currency: row.purchase_currency,
      totalAmount: String(row.purchase_total_amount || ''),
      paidAt: row.purchase_paid_at,
    },
    inventory: {
      totalPaidRolls: Number(row.total_paid_rolls || 0),
      uniquePaidItems: Number(row.unique_paid_items || 0),
      duplicatePaidRolls: Number(row.duplicate_paid_rolls || 0),
    },
  };
}
