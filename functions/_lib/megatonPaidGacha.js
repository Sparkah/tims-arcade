function pad3(value) {
  return String(value).padStart(3, '0');
}

function buildCatalog() {
  const out = [];
  for (const rarity of RARITIES) {
    const seeds = BASE_COLLECTIBLES.filter((row) => row[2] === rarity);
    for (let ordinal = 0; ordinal < RARITY_COUNTS[rarity]; ordinal += 1) {
      const [baseId, baseName, , baseBoostKind] = seeds[ordinal % seeds.length];
      const suffix = ordinal < seeds.length ? '' : pad3(ordinal + 1);
      const baseBoostIndex = BOOSTS.findIndex((boost) => boost[0] === baseBoostKind);
      const boost = BOOSTS[(ordinal + baseBoostIndex) % BOOSTS.length] || BOOSTS[0];
      const values = RARITY_VALUES[rarity];
      out.push(Object.freeze({
        id: suffix ? `${baseId}_${suffix}` : baseId,
        name: suffix ? `${baseName} Mk ${ROMAN[(ordinal - 1) % ROMAN.length]}` : baseName,
        rarity,
        boost: Object.freeze({
          kind: boost[0],
          label: boost[1],
          value: values[ordinal % values.length],
        }),
      }));
    }
  }
  return Object.freeze(out);
}

