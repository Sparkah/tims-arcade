const TABLES: Record<Lang, Record<string, string>> = { en: EN, ru: RU };

export function detectLang(): Lang {
  try {
    const yLang = (window as { ysdk?: { environment?: { i18n?: { lang?: string } } } }).ysdk?.environment?.i18n?.lang;
    const nav = (yLang || navigator.language || 'en').toLowerCase();
    lang = nav.startsWith('ru') ? 'ru' : 'en';
  } catch {
    lang = 'en';
  }
  return lang;
}

export function setLang(next: Lang): void {
  lang = next === 'ru' ? 'ru' : 'en';
}

export function getLang(): Lang {
  return lang;
}

export function t(key: string): string {
  return TABLES[lang][key] ?? TABLES.en[key] ?? key;
}
